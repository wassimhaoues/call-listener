import { describe, expect, it, vi } from "vitest";
import {
  buildDebriefMarkdown,
  debriefFileName,
  downloadMarkdown,
  escapeMarkdownText,
  evidenceLabel,
} from "../src/services/debriefMarkdown.js";

function readBlob(blob) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(reader.result);
    reader.onerror = () => reject(reader.error);
    reader.readAsText(blob);
  });
}

const DATE = new Date(2026, 10, 26, 9, 30);
const EVIDENCE = [{ requirement: "Database migrations", evidence: "Led a billing migration." }];

const REVIEW = {
  questionsCovered: [
    { id: "question-1", question: "Tell me about a migration.", candidateAnswerSummary: "You moved billing to PostgreSQL.", evidenceUsed: ["evidence-1", "evidence-9"] },
    { id: "question-2", question: "Any questions?", candidateAnswerSummary: "", evidenceUsed: [] },
  ],
  strengths: ["Concrete example."],
  improvementTopics: [{ id: "topic-1", topic: "Results", why: "No outcome mentioned.", practiceSuggestion: "End with one number." }],
  followUpDraft: "Server draft.",
};

describe("buildDebriefMarkdown", () => {
  it("renders every section from the review and the edited draft", () => {
    const markdown = buildDebriefMarkdown({ review: REVIEW, followUpDraft: "Thanks again,\nAda", evidence: EVIDENCE, date: DATE });
    expect(markdown).toBe([
      "# Interview review",
      "",
      "Exported 2026-11-26. Generated by AI from the interview transcript; check it before relying on it. Call Listener did not save this review.",
      "",
      "## Questions covered",
      "",
      "1. Tell me about a migration.",
      "   - What you said: You moved billing to PostgreSQL.",
      "   - Evidence used: Database migrations; evidence-9",
      "2. Any questions?",
      "   - What you said: No answer in the transcript.",
      "",
      "## Strengths",
      "",
      "- Concrete example.",
      "",
      "## Topics to improve",
      "",
      "- Results",
      "  - Why: No outcome mentioned.",
      "  - Practice: End with one number.",
      "",
      "## Your notes",
      "",
      "No notes.",
      "",
      "## Follow-up draft",
      "",
      "~~~text",
      "Thanks again,",
      "Ada",
      "~~~",
      "",
    ].join("\n"));
  });

  it("is pure: the same input gives the same file", () => {
    const input = { review: REVIEW, followUpDraft: "Hi", evidence: EVIDENCE, date: DATE };
    expect(buildDebriefMarkdown(input)).toBe(buildDebriefMarkdown(structuredClone(input)));
  });

  it("keeps model text literal: no HTML, links, images, or headings survive", () => {
    const hostile = {
      questionsCovered: [{ question: "<img src=x onerror=alert(1)>", candidateAnswerSummary: "[click](https://evil.test) ![x](y)", evidenceUsed: [] }],
      strengths: ["# Heading\n## injected\n<script>alert(1)</script>"],
      improvementTopics: [],
      followUpDraft: "",
    };
    const markdown = buildDebriefMarkdown({ review: hostile, followUpDraft: "", date: DATE });
    expect(markdown).not.toMatch(/(^|[^\\])<(img|script)/);
    expect(markdown).toContain("\\<img src=x onerror=alert(1)\\>");
    expect(markdown).toContain("\\[click\\](https://evil.test) \\!\\[x\\](y)");
    expect(markdown).toContain("- \\# Heading \\#\\# injected \\<script\\>alert(1)\\</script\\>");
    expect(markdown).not.toContain("&lt;");
    expect(markdown.split("\n").filter((line) => line.startsWith("#"))).toEqual([
      "# Interview review",
      "## Questions covered",
      "## Strengths",
      "## Topics to improve",
      "## Your notes",
      "## Follow-up draft",
    ]);
    expect(markdown).toContain("No draft.");
  });

  it("fences the draft so it cannot close its own block", () => {
    const markdown = buildDebriefMarkdown({ review: REVIEW, followUpDraft: "a\n~~~~\n# not a heading", date: DATE });
    expect(markdown).toContain("~~~~~text\na\n~~~~\n# not a heading\n~~~~~");
  });

  it("falls back to the review's own draft and tolerates an empty review", () => {
    expect(buildDebriefMarkdown({ review: REVIEW, date: DATE })).toContain("~~~text\nServer draft.\n~~~");
    const empty = buildDebriefMarkdown({ review: {}, date: DATE });
    expect(empty).toContain("No questions were identified.");
    expect(empty).toContain("None noted.");
  });
});

describe("helpers", () => {
  it("escapes Markdown syntax and collapses whitespace", () => {
    expect(escapeMarkdownText("  a *b*\n_c_ `d` | e  ")).toBe("a \\*b\\* \\_c\\_ \\`d\\` \\| e");
    expect(escapeMarkdownText(undefined)).toBe("");
  });

  it("maps evidence IDs to requirement names, keeping unknown IDs as-is", () => {
    expect(evidenceLabel("evidence-1", EVIDENCE)).toBe("Database migrations");
    expect(evidenceLabel("evidence-2", EVIDENCE)).toBe("evidence-2");
    expect(evidenceLabel("other", EVIDENCE)).toBe("other");
  });

  it("names the file after the export date", () => {
    expect(debriefFileName(DATE)).toBe("interview-review-2026-11-26.md");
  });
});

describe("downloadMarkdown", () => {
  it("saves through a Blob and a temporary download link, then revokes the URL", async () => {
    const url = { createObjectURL: vi.fn(() => "blob:review"), revokeObjectURL: vi.fn() };
    const scheduled = [];
    const click = vi.spyOn(HTMLAnchorElement.prototype, "click").mockImplementation(function record() {
      expect(this.getAttribute("href")).toBe("blob:review");
      expect(this.download).toBe("interview-review-2026-11-26.md");
      expect(document.body.contains(this)).toBe(true);
    });

    const blob = downloadMarkdown("# Review", "interview-review-2026-11-26.md", {
      url,
      schedule: (fn) => scheduled.push(fn),
    });

    expect(click).toHaveBeenCalledTimes(1);
    expect(url.createObjectURL).toHaveBeenCalledWith(blob);
    expect(blob.type).toBe("text/markdown;charset=utf-8");
    expect(await readBlob(blob)).toBe("# Review");
    expect(document.querySelector("a[download]")).toBeNull();
    scheduled.forEach((fn) => fn());
    expect(url.revokeObjectURL).toHaveBeenCalledWith("blob:review");
    click.mockRestore();
  });
});

describe("self-review notes", () => {
  it("exports the candidate's notes as literal text, with or without an AI review", () => {
    const notes = "Answer on Redis was too long.\n## not a heading <b>x</b>";
    const withReview = buildDebriefMarkdown({ review: { questionsCovered: [], strengths: [], improvementTopics: [] }, selfReviewNotes: notes });
    expect(withReview).toContain("## Your notes\n\n~~~text\n" + notes + "\n~~~");
    const withoutReview = buildDebriefMarkdown({ review: null, selfReviewNotes: notes, date: new Date("2026-11-26T10:00:00Z") });
    expect(withoutReview.split("\n").filter((line) => line.startsWith("#") && !line.startsWith("## not"))).toEqual(["# Interview review", "## Your notes"]);
    expect(withoutReview).toContain("No AI review was available");
    expect(withoutReview).not.toContain("Follow-up draft");
  });
});
