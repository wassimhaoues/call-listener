// Local Markdown export of the unsaved debrief. The file is built in the
// renderer and handed to the browser download flow (Blob + <a download>); no
// IPC, no network request, nothing kept after the download.

// Characters that could start Markdown structure or raw HTML inside a line.
// Backslash-escaping keeps them literal in every CommonMark viewer, so model
// or transcript text can never become a link, an image, or an HTML tag.
const MARKDOWN_SPECIAL = /[\\`*_[\]<>#|!~]/g;

/** One line of literal text: whitespace collapsed, Markdown syntax escaped. */
export function escapeMarkdownText(value) {
  return String(value ?? "")
    .replaceAll(/\s+/g, " ")
    .trim()
    .replaceAll(MARKDOWN_SPECIAL, (char) => "\\" + char);
}

/** A fenced block that the text cannot close: the fence outgrows any `~` run inside. */
function fencedText(value) {
  const body = String(value ?? "").replaceAll(/\r\n?/g, "\n");
  const longestRun = Math.max(0, ...(body.match(/~+/g) || []).map((run) => run.length));
  const fence = "~".repeat(Math.max(3, longestRun + 1));
  return [fence + "text", body, fence].join("\n");
}

/**
 * The candidate-facing label of an evidence ID (`evidence-N` is the N-th
 * evidence reference in the candidate's interview context).
 */
export function evidenceLabel(id, evidence = []) {
  const match = /^evidence-(\d{1,3})$/.exec(String(id));
  const item = match ? evidence[Number(match[1]) - 1] : undefined;
  return item?.requirement ? String(item.requirement) : String(id);
}

function pad(value) {
  return String(value).padStart(2, "0");
}

export function formatReviewDate(date = new Date()) {
  return [date.getFullYear(), pad(date.getMonth() + 1), pad(date.getDate())].join("-");
}

export function debriefFileName(date = new Date()) {
  return "interview-review-" + formatReviewDate(date) + ".md";
}

function questionLines(item, index, evidence) {
  const lines = [String(index + 1) + ". " + escapeMarkdownText(item.question)];
  const summary = item.candidateAnswerSummary || "No answer in the transcript.";
  lines.push("   - What you said: " + escapeMarkdownText(summary));
  if (item.evidenceUsed?.length) {
    const labels = item.evidenceUsed.map((id) => escapeMarkdownText(evidenceLabel(id, evidence)));
    lines.push("   - Evidence used: " + labels.join("; "));
  }
  return lines;
}

function topicLines(item) {
  const lines = ["- " + escapeMarkdownText(item.topic)];
  if (item.why) lines.push("  - Why: " + escapeMarkdownText(item.why));
  if (item.practiceSuggestion) lines.push("  - Practice: " + escapeMarkdownText(item.practiceSuggestion));
  return lines;
}

function section(title, lines, emptyText) {
  return ["## " + title, "", ...(lines.length ? lines : [emptyText]), ""];
}

/**
 * Build the Markdown file for a review. Pure: the same input always gives the
 * same text. All review text is escaped as literal Markdown; nothing is
 * converted to HTML.
 *
 * @param {{ review: object, followUpDraft?: string, evidence?: Array<{ requirement: string }>, date?: Date }} input
 */
export function buildDebriefMarkdown({ review, followUpDraft, evidence = [], date = new Date() }) {
  const questions = (review?.questionsCovered || []).flatMap((item, index) => questionLines(item, index, evidence));
  const strengths = (review?.strengths || []).map((item) => "- " + escapeMarkdownText(item));
  const topics = (review?.improvementTopics || []).flatMap(topicLines);
  const draft = String(followUpDraft ?? review?.followUpDraft ?? "");
  return [
    "# Interview review",
    "",
    "Exported " + formatReviewDate(date) + ". Generated by AI from the interview transcript; " +
      "check it before relying on it. Call Listener did not save this review.",
    "",
    ...section("Questions covered", questions, "No questions were identified."),
    ...section("Strengths", strengths, "None noted."),
    ...section("Topics to improve", topics, "None noted."),
    "## Follow-up draft",
    "",
    draft.trim() ? fencedText(draft) : "No draft.",
    "",
  ].join("\n");
}

/**
 * Hand `markdown` to the download flow as `fileName`. Dependencies are
 * injectable for tests; nothing is stored, and the object URL is revoked.
 */
export function downloadMarkdown(markdown, fileName, { doc = document, url = URL, schedule = setTimeout } = {}) {
  const blob = new Blob([markdown], { type: "text/markdown;charset=utf-8" });
  const href = url.createObjectURL(blob);
  const link = doc.createElement("a");
  link.href = href;
  link.download = fileName;
  link.rel = "noopener";
  link.style.display = "none";
  doc.body.appendChild(link);
  try {
    link.click();
  } finally {
    link.remove();
    schedule(() => url.revokeObjectURL(href), 0);
  }
  return blob;
}
